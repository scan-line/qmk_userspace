void init_lcd_styles(void) {
  // Colors mimic an old-style lcd display.
  lv_style_init(&base);
  lv_style_set_bg_opa(&base, LV_OPA_COVER);
  lv_style_set_bg_color(&base, lv_color_hex(0xb2c2af));
  lv_style_set_text_color(&base, lv_color_hex(0x667079));
  lv_style_set_text_align(&base, LV_TEXT_ALIGN_CENTER);
  lv_style_set_text_font(&base, &source_code_pro_medium_24);

  lv_style_init(&plain);
  lv_style_set_border_width(&plain, 0);
  lv_style_set_radius(&plain, 0);
  lv_style_set_pad_all(&plain, 0);
}

lv_obj_t* rect_create(lv_obj_t* parent) {
  lv_obj_t* obj = lv_obj_create(parent);
  lv_obj_add_style(obj, &plain, LV_PART_MAIN);
  lv_obj_add_style(obj, &base, LV_PART_MAIN);
  return obj;
}


