void luna_init(void) {
  // A 64x64 container, allowing for jump.
  luna = rect_create(lv_scr_act());
  lv_obj_set_size(luna, 64, 64);

  // Frame moves up and down within parent as luna jumps.
  luna_image = lv_img_create(luna);
  lv_img_set_zoom(luna_image, 256*2);
  lv_img_set_src(luna_image, luna_sit[0]);
  lv_obj_align(luna_image, LV_ALIGN_CENTER, 0, +10);
}

void luna_animate(void) {
  if (is_jumping || show_jump) {
    lv_obj_align(luna_image, LV_ALIGN_CENTER, 0, -10);
    show_jump = false;
  } else {
    lv_obj_align(luna_image, LV_ALIGN_CENTER, 0, +10);
  }

  // Switch frame
  static uint8_t current_frame = 0;
  current_frame = (current_frame + 1) % 2;

  // Current status
  const int current_wpm = get_current_wpm();
  const led_t led_state = host_keyboard_led_state();
  const bool is_sneaking = (get_mods() | get_weak_mods() | get_oneshot_mods()) & (MOD_MASK_CTRL | MOD_MASK_GUI);

  if (led_state.caps_lock || is_caps_word_on()) {
    lv_img_set_src(luna_image, luna_bark[current_frame]);
  } else if (is_sneaking) {
    lv_img_set_src(luna_image, luna_sneak[current_frame]);
  } else if (current_wpm <= MIN_WALK_SPEED) {
    lv_img_set_src(luna_image, luna_sit[current_frame]);
  } else if (current_wpm <= MIN_RUN_SPEED) {
    lv_img_set_src(luna_image, luna_walk[current_frame]);
  } else {
    lv_img_set_src(luna_image, luna_run[current_frame]);
  }
}

void luna_render(void) {
  // Animation timer
  static uint32_t anim_timer = 0;
  if (timer_elapsed32(anim_timer) > ANIM_FRAME_DURATION) {
    anim_timer = timer_read32();
    luna_animate();
  }
}

void process_record_luna(uint16_t keycode, keyrecord_t *record) {
  // Space is also on LT(U_NAV,KC_SPC)
  if (IS_QK_LAYER_TAP(keycode) && record->tap.count > 0) {
    keycode = QK_LAYER_TAP_GET_TAP_KEYCODE(keycode);
  }

  switch (keycode) {
    case KC_SPC:
      if (record->event.pressed) {
        is_jumping = true;
        show_jump = true;
      } else {
        is_jumping = false;
      }
      break;
    default:
      break;
  }
}


// Feedback

lv_obj_t* message = 0;

const char message_empty[] = "";
const char* message_base = message_empty;
const char* message_cur = message_empty;

bool message_timeout = false;
uint32_t message_timer = 0;


void message_init(void) {
  message = lv_label_create(lv_scr_act());
  lv_obj_add_style(message, &base, LV_PART_MAIN);
  lv_obj_set_width(message, 64);
  lv_label_set_text(message, message_cur);
}

void message_label_set(const char* str) {
  if (message) {
    message_cur = str;
    lv_label_set_text(message, message_cur);
  }
}

void message_set(const char* str) {
  message_base = str;
  message_label_set(str);
}

void message_flash(const char* str) {
  message_timeout = true;
  message_timer = timer_read32();
  message_label_set(str);
}

void message_render(void) {
  if (message_timeout && timer_elapsed32(message_timer) > FEEDBACK_TIMEOUT) {
    message_timeout = false;
    message_label_set(message_base);
  }
}

void show_os_mode_keymap(uint16_t keycode) {
  switch (keycode) {
    case U_WIN:
      message_flash("win");
      break;
    case U_MAC:
      message_flash("mac");
      break;
    case U_LNX:
      message_flash("lnx");
      break;
    default:
      break;
  }
}

void show_layer_keymap(uint8_t layer, uint8_t default_layer) {
  switch (layer) {
    case U_BASE:
      message_set("cmk");
      break;
    case U_EXTRA:
      message_set("qty");
      break;
    case U_TAP:
      message_set("tap");
      break;
    case U_BUTTON:
      message_set("btn");
      break;
    case U_NAV:
      message_set("nav");
      break;
    case U_MOUSE:
      message_set("mse");
      break;
    case U_MEDIA:
      message_set("med");
      break;
    case U_NUM:
      message_set("num");
      break;
    case U_SYM:
      message_set("sym");
      break;
    case U_FUN:
      message_set("fun");
      break;
    default:
      message_set(message_empty);
      break;
  }
}

void show_toggle_keymap(uint16_t keycode, bool value) {
  if (value)
    message_flash("[x]");
  else
    message_flash("[ ]");
}

void show_value_keymap(uint16_t keycode, uint8_t value, bool detent) {
  static char buffer[5 + 1];
  if (detent)
    sprintf(buffer, "=%d=", value);
  else
    sprintf(buffer, "%d", value);
  message_flash(buffer);
}


