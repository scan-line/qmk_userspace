painter_device_t lcd;

void lcd_init_master(void) {
  lv_obj_add_style(lv_scr_act(), &base, LV_PART_MAIN);

  luna_init();
  lv_obj_align(luna, LV_ALIGN_TOP_MID, 0, 20);

  message_init();
  lv_obj_align(message, LV_ALIGN_TOP_MID, 0, 110);

  const uint8_t layer = get_highest_layer(layer_state|default_layer_state);
  const uint8_t default_layer = get_highest_layer(default_layer_state);
  show_layer_keymap(layer, default_layer);
}

void lcd_init_slave(void) {
  lv_obj_add_style(lv_scr_act(), &base, LV_PART_MAIN);

  // A 60x60 container, allowing for image scale.
  lv_obj_t* miryoku = rect_create(lv_scr_act());
  lv_obj_set_size(miryoku, 60, 60);
  // Align with luna base.
  lv_obj_align(miryoku, LV_ALIGN_TOP_MID, 0, 24);

  lv_obj_t* miryoku_image = lv_img_create(miryoku);
  lv_img_set_zoom(miryoku_image, 256*2);
  lv_img_set_src(miryoku_image, &miryoku_logo);
  lv_obj_align(miryoku_image, LV_ALIGN_CENTER, 0, 0);

  info_init();
  lv_obj_align(info, LV_ALIGN_TOP_MID, 0, 110);
}

void lcd_init(void) {
  // Initialise the lcd
  wait_ms(LCD_WAIT_TIME);
  lcd = qp_st7735_make_spi_device(LCD_WIDTH, LCD_HEIGHT, LCD_CS_PIN, LCD_DC_PIN, LCD_RST_PIN, LCD_SPI_DIVISOR, LCD_SPI_MODE);
  qp_init(lcd, LCD_ROTATION);
  qp_set_viewport_offsets(lcd, LCD_OFFSET_X, LCD_OFFSET_Y);

#ifdef LCD_INVERT_COLOUR
  qp_comms_start(lcd);
  qp_comms_command(lcd, ST77XX_CMD_INVERT_ON);
  qp_comms_stop(lcd);
#endif

  if (!qp_lvgl_attach(lcd))
    return;

  init_lcd_styles();
  if (is_keyboard_master())
    lcd_init_master();
  else
    lcd_init_slave();
}

void lcd_task_master(void) {
  luna_render();
  message_render();
}

void lcd_task_slave(void) {
}

void lcd_housekeeping_task(void) {
  if (is_keyboard_master()) {
    lcd_task_master();
  } else {
    lcd_task_slave();
  }
}

void suspend_power_down_keymap(void) {
  // May be run multiple times on suspend
  qp_power(lcd, false);
}

void suspend_wakeup_init_keymap(void) {
  qp_power(lcd, true);
}
